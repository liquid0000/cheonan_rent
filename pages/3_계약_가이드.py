# 2) 최우선변제 자가진단
#    주택임대차보호법 시행령 제10조, 제11조 (2023.2.21 이후 설정된 담보물권 기준)
#    천안시는 서울/과밀억제권역/광역시 등에 해당하지 않아 '그 밖의 지역' 기준을 적용
# ---------------------------------------------------------------
SMALL_LIMIT = 7500    # 소액임차인 보증금 기준 (만원)
PRIORITY_MAX = 2500   # 최우선변제 최대 금액 (만원)

with tab2:
    st.write("집이 경매로 넘어가도, 보증금이 일정 금액 이하인 세입자(소액임차인)는 "
             "다른 빚보다 먼저 일정 금액을 돌려받을 수 있습니다. 이를 **최우선변제**라고 합니다.")
    st.markdown(f"""
| 구분 (천안시 = 그 밖의 지역) | 기준 |
|---|---|
| 소액임차인 보증금 기준 | {SMALL_LIMIT:,}만 원 이하 |
| 먼저 돌려받는 최대 금액 | {PRIORITY_MAX:,}만 원 |
""")
    deposit = st.number_input("내 보증금 (만원)", min_value=0, max_value=50000, value=300, step=50)
    moved_in = st.checkbox("전입신고를 했고 실제로 살고 있다", value=True)

    if not moved_in:
        st.error("전입신고와 실제 거주가 없으면 최우선변제를 받을 수 없습니다. 이사 당일 전입신고부터 하세요.")
    elif deposit <= PRIORITY_MAX:
        st.success(f"보증금 {deposit:,}만 원 전액이 최우선변제 범위 안에 있습니다.")
    elif deposit <= SMALL_LIMIT:
        st.warning(f"소액임차인에 해당합니다. 보증금 {deposit:,}만 원 중 최대 {PRIORITY_MAX:,}만 원까지 먼저 돌려받을 수 있고, "
                   f"나머지 {deposit - PRIORITY_MAX:,}만 원은 확정일자 순서에 따라 받게 됩니다.")
    else:
        st.error(f"보증금이 {SMALL_LIMIT:,}만 원을 넘어 최우선변제 대상이 아닙니다. 확정일자와 등기부등본의 선순위 빚을 꼭 확인하고, "
                 "전세보증금 반환보증 가입을 검토하세요.")

    st.caption("주의: 최우선변제는 집값(경매 낙찰가)의 절반 안에서만 인정되고, 같은 집 세입자들이 나눠 받습니다. "
               "또 등기부등본의 근저당이 2023년 2월 21일 이전에 설정됐다면 그 당시의 더 낮은 기준이 적용될 수 있습니다. "
               "근거: 주택임대차보호법 제8조, 시행령 제10조와 제11조")

